import io.qalipsis.test.mockk.WithMockk
import io.qalipsis.test.mockk.relaxedMockk
import io.qalipsis.test.steps.AbstractStepSpecificationConverterTest
import org.junit.jupiter.api.Assertions
import org.junit.jupiter.api.Test


/**
 * @author Carlos Vieira
 */
@WithMockk
@Suppress("UNCHECKED_CAST")
internal class SqlSaveStepSpecificationConverterTest :
    AbstractStepSpecificationConverterTest<SqlSaveStepSpecificationConverter>() {

    @Test
    override fun `should not support unexpected spec`() {
        Assertions.assertFalse(converter.support(relaxedMockk()))
    }

    @Test
    override fun `should support expected spec`() {
        Assertions.assertTrue(converter.support(relaxedMockk<SqlSaveStepSpecificationImpl<*>>()))
    }
}
